SELECT *
FROM orders
WHERE status != 'Отменён' AND
category IN ('Электроника', 'Аудио', 'Бытовая техника') AND
price BETWEEN 8000 AND 100000 AND
discount = :'user_discount'
ORDER BY price DESC, order_date DESC
LIMIT 5;

--2
SELECT DISTINCT category, status
FROM orders
WHERE product ILIKE '%а%' AND
(quantity > 1 OR
price > 20000) AND
status != 'Отменён' AND
category IN ('Аксессуары', 'Периферия', 'Аудио', 'Электроника')
ORDER BY category, status DESC;

--3
SELECT *
FROM orders
WHERE status != 'Отменён' AND
price > 3000 AND
product NOT ILIKE 'к%' AND
(discount >= 10 OR discount IS NULL)
ORDER BY (discount IS NOT NULL) ASC, price DESC
OFFSET 2 LIMIT 5;

